// SGPortable: single-file launcher for the ShellGate portable bundle.
// Embeds shellgate.exe, cloudflared.exe and ShellGate.hta (gzip-compressed),
// extracts them to %TEMP%\SGPortable on first run, prepares shellgate.env
// (copied from next to this exe when present, otherwise a template with a
// freshly generated token), then opens the HTA control panel and exits.
// The env file (user config with secrets) is NEVER embedded.
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/rand"
	_ "embed"
	"encoding/hex"
	"io"
	"os"
	"os/exec"
	"path/filepath"
)

//go:embed payloads/shellgate.exe.gz
var shellgateGZ []byte

//go:embed payloads/cloudflared.exe.gz
var cloudflaredGZ []byte

//go:embed payloads/ShellGate.hta.gz
var htaGZ []byte

//go:embed payloads/shellgate.ico.gz
var icoGZ []byte

//go:embed payloads/SGPanelHost.exe.gz
var hostGZ []byte

func gunzip(data []byte) ([]byte, error) {
	r, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return nil, err
	}
	defer r.Close()
	return io.ReadAll(r)
}

// extract writes data to dir/name, skipping the write when an existing
// file already has the same size.
func extract(dir, name string, data []byte) error {
	target := filepath.Join(dir, name)
	if st, err := os.Stat(target); err == nil && st.Size() == int64(len(data)) {
		return nil
	}
	return os.WriteFile(target, data, 0o755)
}

func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}

func genToken() string {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return ""
	}
	return hex.EncodeToString(b)
}

func writeTemplateEnv(path string) error {
	tok := genToken()
	content := "# ShellGate config (auto-generated by SGPortable on first run)\r\n" +
		"# token: access token for the panel / MCP clients; change it if you like (min 32 chars)\r\n" +
		"token=" + tok + "\r\n" +
		"net=tunnel\r\n" +
		"admin_port=0\r\n" +
		"# tunnel_token: paste the Cloudflare tunnel token on the next line (uncomment it),\r\n" +
		"# or fill it in later from the admin page's Cloudflare wizard.\r\n" +
		"# tunnel_token=\r\n"
	return os.WriteFile(path, []byte(content), 0o644)
}

func main() {
	exePath, err := os.Executable()
	if err != nil {
		return
	}
	exeDir := filepath.Dir(exePath)

	tmpBase := os.Getenv("TEMP")
	if tmpBase == "" {
		tmpBase = os.TempDir()
	}
	workDir := filepath.Join(tmpBase, "SGPortable")
	if err := os.MkdirAll(workDir, 0o755); err != nil {
		return
	}

	payloads := []struct {
		name string
		gz   []byte
	}{
		{"shellgate.exe", shellgateGZ},
		{"cloudflared.exe", cloudflaredGZ},
		{"ShellGate.html", htaGZ},
		{"shellgate.ico", icoGZ},
		{"SGPanelHost.exe", hostGZ},
	}
	for _, p := range payloads {
		raw, err := gunzip(p.gz)
		if err != nil {
			return
		}
		if err := extract(workDir, p.name, raw); err != nil {
			return
		}
	}

	// Config: an env sitting next to SGPortable.exe is the master copy and
	// wins on every launch; otherwise keep the workdir env, generating a
	// template only when there is none at all.
	dstEnv := filepath.Join(workDir, "shellgate.env")
	srcEnv := filepath.Join(exeDir, "shellgate.env")
	if _, err := os.Stat(srcEnv); err == nil {
		_ = copyFile(srcEnv, dstEnv)
	} else if _, err := os.Stat(dstEnv); os.IsNotExist(err) {
		_ = writeTemplateEnv(dstEnv)
	}

	// Open the control panel in our own host window (SGPanelHost embeds
	// MSHTML: the panel gets this bundle's icon and HTA-equivalent trust
	// without mshta.exe); do not wait for it.
	htaPath := filepath.Join(workDir, "ShellGate.html")
	hostPath := filepath.Join(workDir, "SGPanelHost.exe")
	cmd := exec.Command(hostPath, htaPath)
	cmd.Dir = workDir
	_ = cmd.Start()
}

